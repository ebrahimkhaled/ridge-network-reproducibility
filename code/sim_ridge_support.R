## ---------------------------------------------------------------------------
## 1. Ridge building blocks
## ---------------------------------------------------------------------------

## Spectral decomposition of S, computed once and reused for every penalty.
## For p > n the p - rank(S) zero eigenvalues are kept; on that null space
## (S + lambda I)^{-1} acts as I / lambda.
spec_S <- function(S) {
  e <- eigen(S, symmetric = TRUE)
  list(vec = e$vectors, val = pmax(e$values, 0))
}

## Archetypal ridge precision estimator Q = (S + lambda I)^{-1}.
ridge_Q <- function(sp, lambda) sp$vec %*% (t(sp$vec) / (sp$val + lambda))

## Partial correlations rho_ij = -A_ij / sqrt(A_ii A_jj). They are invariant
## under A -> c A, c > 0, so the factor 1 + delta_n separating E Q from
## Theta_kappa does not enter them.
pcor_of <- function(A) {
  d <- 1 / sqrt(diag(A))
  R <- -A * outer(d, d)
  diag(R) <- 1
  R
}

## r_hat = tr{S (S + lambda I)^{-1}} / n. Its complement s_hat = 1 - r_hat
## estimates 1 / (1 + delta_n), and kappa_hat = lambda / s_hat estimates the
## effective penalty kappa_n = lambda (1 + delta_n).
r_hat <- function(sp, lambda, n) sum(sp$val / (sp$val + lambda)) / n
## 1 - r_hat is evaluated as (n - r) / n + (lambda / n) sum_{s_j > 0} 1 / (s_j +
## lambda), r = rank(S), which avoids cancellation when lambda is small
s_hat <- function(sp, lambda, n, tol = 1e-10) {
  pos <- sp$val[sp$val > tol * max(sp$val)]
  (n - length(pos)) / n + lambda * sum(1 / (pos + lambda)) / n
}
kappa_hat <- function(sp, lambda, n) lambda / s_hat(sp, lambda, n)

## kappa_hat is continuous and strictly increasing in lambda, so the penalty
## attaining a prescribed effective penalty is found by bracketing.
lambda_for_kappa <- function(sp, n, kappa_target, lower = 1e-10) {
  f <- function(l) kappa_hat(sp, l, n) - kappa_target
  uniroot(f, c(lower, 1e6), tol = 1e-12)$root
}

## Two-point extrapolation across effective penalties (Section 6 of the
## paper). With kappa_2 = cfac * kappa_1 the combination
## w1 s1 Q1 + w2 s2 Q2, w1 = k2 / (k2 - k1), w2 = -k1 / (k2 - k1), removes the
## part of the bias Theta_kappa - Theta that is linear in kappa.
richardson_Q <- function(sp, n, lambda1, cfac = 2) {
  k1 <- kappa_hat(sp, lambda1, n)
  ## kappa_hat is increasing, so the root lies above lambda1
  lambda2 <- lambda_for_kappa(sp, n, cfac * k1, lower = lambda1)
  k2 <- kappa_hat(sp, lambda2, n)
  s1 <- s_hat(sp, lambda1, n)
  s2 <- s_hat(sp, lambda2, n)
  w1 <- k2 / (k2 - k1)
  w2 <- -k1 / (k2 - k1)
  list(T = w1 * s1 * ridge_Q(sp, lambda1) + w2 * s2 * ridge_Q(sp, lambda2),
       kappa = c(k1, k2))
}

## Type-I alternative ridge estimator with null target (van Wieringen and
## Peeters, 2016): [ (lambda I + S^2 / 4)^{1/2} + S / 2 ]^{-1}.
altridge_Q <- function(sp, lambda) {
  d <- sqrt(lambda + sp$val^2 / 4) + sp$val / 2
  sp$vec %*% (t(sp$vec) / d)
}

## K-fold cross-validated Gaussian negative log-likelihood over a penalty
## grid; the held-out loss is tr(S_test Q) - log det Q with Q from the
## training folds.
cv_lambda <- function(X, grid, K = 5, type = c("ridge", "alt")) {
  type <- match.arg(type)
  n <- nrow(X)
  fold <- sample(rep_len(1:K, n))
  loss <- matrix(0, K, length(grid))
  for (k in 1:K) {
    Xtr <- X[fold != k, , drop = FALSE]
    Xte <- X[fold == k, , drop = FALSE]
    sp <- spec_S(crossprod(Xtr) / nrow(Xtr))
    Ste <- crossprod(Xte) / nrow(Xte)
    ste_diag <- colSums(sp$vec * (Ste %*% sp$vec))
    for (g in seq_along(grid)) {
      dv <- if (type == "ridge") 1 / (sp$val + grid[g])
            else 1 / (sqrt(grid[g] + sp$val^2 / 4) + sp$val / 2)
      loss[k, g] <- sum(ste_diag * dv) - sum(log(dv))
    }
  }
  grid[which.min(colMeans(loss))]
}

## ---------------------------------------------------------------------------
## 2. Edge-selection layers
## ---------------------------------------------------------------------------

## Local-FDR sparsification (Schafer and Strimmer, 2005; van Wieringen and
## Peeters, 2016): keep an edge when 1 - lfdr >= cut.
lfdr_select <- function(R, cut = 0.9) {
  ut <- upper.tri(R)
  fit <- fdrtool(R[ut], statistic = "correlation", plot = FALSE,
                 verbose = FALSE)
  A <- matrix(FALSE, nrow(R), ncol(R))
  A[ut] <- (1 - fit$lfdr) >= cut
  A | t(A)
}

## Multi-penalty permutation selection. For each penalty lambda_g in the grid
## MULT * tr(S) / p the maximal absolute ridge partial correlation is
## calibrated against NPERM column-wise permutations of X, at level
## alpha / |grid|; an edge is selected if it exceeds the threshold at some
## penalty. tr(S) is invariant under column-wise permutation, so under complete
## independence the probability of selecting any edge is at most alpha, for
## every n and p (Proposition 5 of the paper).
mps_select <- function(X, mult = MULT, B = NPERM, alpha = ALPHA) {
  n <- nrow(X) - 1; p <- ncol(X); ut <- upper.tri(diag(p))
  S <- crossprod(X) / n                 # X is column-centred, n = rows - 1
  lams <- mult * sum(diag(S)) / p
  sp <- spec_S(S)
  Robs <- lapply(lams, function(l) pcor_of(ridge_Q(sp, l)))
  Tobs <- sapply(Robs, function(R) max(abs(R[ut])))
  Tb <- matrix(0, B, length(lams))
  for (b in 1:B) {
    Xb <- scale(apply(X, 2, sample), center = TRUE, scale = FALSE)
    spb <- spec_S(crossprod(Xb) / n)
    Tb[b, ] <- sapply(lams, function(l)
      max(abs(pcor_of(ridge_Q(spb, l))[ut])))
  }
  k <- ceiling((1 - alpha / length(lams)) * (B + 1))
  A <- matrix(FALSE, p, p)
  tau <- numeric(length(lams))
  for (g in seq_along(lams)) {
    tau[g] <- sort(c(Tobs[g], Tb[, g]))[k]
    A <- A | (abs(Robs[[g]]) > tau[g])
  }
  diag(A) <- FALSE
  list(A = A, R = Robs, lambda = lams, tau = tau)
}

## Ridge screening followed by nodewise lasso refit. For node j the candidate
## neighbours are the d_n variables with the largest |rho_hat_jk|; the lasso
## on the candidates is tuned by the extended BIC of Chen and Chen (2008),
## gamma = 1; the AND rule symmetrises.
screen_refit <- function(X, R, dn) {
  p <- ncol(X); n <- nrow(X)
  B <- matrix(FALSE, p, p)
  for (j in 1:p) {
    r <- abs(R[j, ]); r[j] <- -Inf
    cand <- order(r, decreasing = TRUE)[1:dn]
    fit <- glmnet(X[, cand, drop = FALSE], X[, j], intercept = FALSE,
                  standardize = TRUE, nlambda = 50)
    rss <- colSums((X[, j] - predict(fit, X[, cand, drop = FALSE]))^2)
    ebic <- n * log(rss / n) + fit$df * (log(n) + 2 * log(dn))
    b <- as.numeric(coef(fit, s = fit$lambda[which.min(ebic)]))[-1]
    B[j, cand[b != 0]] <- TRUE
  }
  B & t(B)
}

## Graphical lasso along the huge path, tuned by the extended BIC of Foygel
## and Drton (2010) with gamma = 0.5.
## huge() standardizes the data and fits the path to cor(X), so the
## likelihood in the EBIC is evaluated at cor(X), the matrix that was fitted
## (the argument S is kept for compatibility and no longer used).
glasso_ebic <- function(X, S, nlambda = 30, gamma = 0.5) {
  n <- nrow(X); p <- ncol(X)
  S <- cor(X)
  h <- huge(X, method = "glasso", nlambda = nlambda, lambda.min.ratio = 0.01,
            verbose = FALSE)
  eb <- sapply(seq_along(h$lambda), function(k) {
    Om <- as.matrix(h$icov[[k]])
    ne <- (sum(abs(Om) > 1e-10) - p) / 2
    ld <- as.numeric(determinant(Om, logarithm = TRUE)$modulus)
    n * (sum(S * Om) - ld) + ne * log(n) + 4 * gamma * ne * log(p)
  })
  list(path = lapply(h$path, function(A) as.matrix(A) != 0),
       sel = as.matrix(h$path[[which.min(eb)]]) != 0)
}

## ---------------------------------------------------------------------------
## 3. Performance measures
## ---------------------------------------------------------------------------

sel_metrics <- function(A, E) {
  ut <- upper.tri(E)
  a <- A[ut]; e <- E[ut]
  tp <- sum(a & e); fp <- sum(a & !e); fn <- sum(!a & e); tn <- sum(!a & !e)
  den <- sqrt(tp + fp) * sqrt(tp + fn) * sqrt(tn + fp) * sqrt(tn + fn)
  c(TPR = tp / max(1, tp + fn), FDP = fp / max(1, tp + fp),
    MCC = if (den > 0) (tp * tn - fp * fn) / den else 0, NE = tp + fp)
}

## Threshold-free summaries: area under the ROC curve (Mann-Whitney form) and
## the separation margin min_{edges}|rho| - max_{non-edges}|rho|; a positive
## margin means that some threshold recovers the edge set exactly.
rank_metrics <- function(R, E) {
  ut <- upper.tri(E)
  s <- abs(R[ut]); e <- E[ut]
  n1 <- sum(e); n0 <- sum(!e)
  auc <- (sum(rank(s)[e]) - n1 * (n1 + 1) / 2) / (n1 * n0)
  c(AUC = auc, MARGIN = min(s[e]) - max(s[!e]))
}

## Best attainable MCC along a path of graphs, or over all thresholds of a
## partial-correlation matrix (computed exactly from the sorted scores).
oracle_mcc <- function(path, E) {
  max(sapply(path, function(A) { diag(A) <- FALSE; sel_metrics(A, E)["MCC"] }))
}
oracle_mcc_threshold <- function(R, E) {
  ut <- upper.tri(E)
  s <- abs(R[ut]); e <- E[ut]
  o <- order(s, decreasing = TRUE)
  tp <- cumsum(e[o]); fp <- cumsum(!e[o])
  P <- sum(e); N <- sum(!e)
  fn <- P - tp; tn <- N - fp
  den <- sqrt(tp + fp) * sqrt(tp + fn) * sqrt(tn + fp) * sqrt(tn + fn)
  mcc <- ifelse(den > 0, (tp * tn - fp * fn) / den, 0)
  max(mcc)
}

## Graph distances in the true graph, used to stratify leakage.
graph_dist <- function(E) {
  g <- graph_from_adjacency_matrix(E * 1, mode = "undirected")
  D <- distances(g)
  D[is.infinite(D)] <- 99
  D
}

## ---------------------------------------------------------------------------
## 4. One Monte Carlo replicate
## ---------------------------------------------------------------------------

one_rep <- function(n, Sig, Theta, E, D) {
  p <- ncol(Sig)
  X <- matrix(rnorm(n * p), n, p) %*% chol(Sig)
  X <- scale(X, center = TRUE, scale = FALSE)
  ## After centring, S = X'X / (n - 1) has the law of a sample covariance of
  ## n - 1 independent N_p(0, Sigma) vectors (Helmert transformation), so the
  ## effective-penalty formulas are applied with n_eff = n - 1.
  neff <- n - 1
  S <- crossprod(X) / neff
  sp <- spec_S(S)
  ut <- upper.tri(E)
  grid <- exp(seq(log(1e-2), log(20), length.out = 30))

  ## plain ridge with likelihood cross-validated penalty
  lam <- cv_lambda(X, grid, type = "ridge")
  R_plain <- pcor_of(ridge_Q(sp, lam))
  kap <- kappa_hat(sp, lam, neff)

  ## extrapolated (debiased) ridge, kappa_2 = 2 kappa_1
  RR <- richardson_Q(sp, neff, lam, cfac = 2)
  R_rich <- pcor_of(RR$T)

  ## van Wieringen-Peeters type-I ridge with its own cross-validated penalty
  lam_a <- cv_lambda(X, grid, type = "alt")
  R_alt <- pcor_of(altridge_Q(sp, lam_a))

  ## population ridge graph at the estimated effective penalty
  R_kap <- pcor_of(solve(Sig + kap * diag(p)))

  mps <- mps_select(X)
  gl <- glasso_ebic(X, S)
  hmb <- huge(X, method = "mb", nlambda = 30, lambda.min.ratio = 0.01,
              verbose = FALSE)
  mb_sel <- as.matrix(huge.select(hmb, criterion = "ric",
                                  verbose = FALSE)$refit) != 0

  sel <- list(
    vWP_lFDR = lfdr_select(R_alt),
    RT_lFDR  = lfdr_select(R_plain),
    RE_lFDR  = lfdr_select(R_rich),
    RS_lasso = screen_refit(X, R_plain, dn = min(p - 1, ceiling(n / log(n)))),
    RT_MPS   = mps$A,
    GLASSO   = gl$sel,
    MB       = mb_sel)
  for (k in names(sel)) diag(sel[[k]]) <- FALSE
  met <- t(sapply(sel, sel_metrics, E = E))

  ## tuning-free comparison
  orc <- c(RT = oracle_mcc_threshold(R_plain, E),
           RE = oracle_mcc_threshold(R_rich, E),
           vWP = oracle_mcc_threshold(R_alt, E),
           GLASSO = oracle_mcc(gl$path, E),
           MB = oracle_mcc(lapply(hmb$path, function(A) as.matrix(A) != 0), E))
  ## penalty sensitivity: oracle MCC and kappa_hat on the MPS grid
  sens <- rbind(mcc = sapply(mps$R, oracle_mcc_threshold, E = E),
                kappa = sapply(mps$lambda, kappa_hat, sp = sp, n = neff))

  rk <- rbind(RT = rank_metrics(R_plain, E), RE = rank_metrics(R_rich, E),
              vWP = rank_metrics(R_alt, E))

  ## leakage by graph distance: observed mean |rho_hat| and Theta_kappa values
  dd <- factor(pmin(D[ut], 4), levels = 1:4)
  leak <- rbind(obs  = tapply(abs(R_plain[ut]), dd, mean),
                pred = tapply(abs(R_kap[ut]), dd, mean),
                rich = tapply(abs(R_rich[ut]), dd, mean))

  sig_min <- min(eigen(Sig, symmetric = TRUE, only.values = TRUE)$values)
  list(met = met, rk = rk, leak = leak, orc = orc, sens = sens,
       info = c(lambda = lam, kappa = kap, kappa2 = RR$kappa[2],
                floor = lam + sig_min * max(0, p - neff + 1) / neff,
                maxdev = max(abs(R_plain - R_kap)[ut])))
}

## Run nrep calls of fun() on nstream L'Ecuyer streams derived from the
## current seed. Stream i (nextRNGStream applied i times) runs replicates
## i, i + nstream, ... sequentially; this is what mclapply(mc.cores =
## nstream, mc.set.seed = TRUE) does, so the output does not depend on the
## number of cores actually used.
run_streams <- function(nrep, nstream, fun) {
  s <- .Random.seed
  seeds <- vector("list", nstream)
  for (i in seq_len(nstream)) { s <- parallel::nextRNGStream(s); seeds[[i]] <- s }
  chain <- function(i) {
    assign(".Random.seed", seeds[[i]], envir = .GlobalEnv)
    lapply(seq(i, nrep, by = nstream), function(r) fun())
  }
  out <- if (NCORE > 1) mclapply(seq_len(nstream), chain, mc.cores = NCORE,
                                 mc.set.seed = FALSE)
         else lapply(seq_len(nstream), chain)
  reps <- vector("list", nrep)
  for (i in seq_len(nstream)) reps[seq(i, nrep, by = nstream)] <- out[[i]]
  reps
}

