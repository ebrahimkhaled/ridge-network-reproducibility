###############################################################################
## Simulation study for
##   "What does a ridge network estimate? Effective penalty, leakage and
##    support recovery for ridge precision matrix estimators"
##
## Author : M. Arashi
## Purpose: Monte Carlo evaluation of edge selection built on the ridge
##          precision estimator Q = (S + lambda I)^{-1}. Three support-recovery
##          layers on top of the same ridge fit are compared (local-FDR
##          testing, extrapolated (debiased) thresholding, ridge screening with
##          nodewise refit) together with a permutation-calibrated
##          multi-penalty threshold, the lFDR procedure of van Wieringen and
##          Peeters (2016), the graphical lasso and neighbourhood selection.
##          The script also produces the effective-penalty and leakage checks
##          of the theory, the penalty-sensitivity study and the (n, p) timing
##          benchmark.
##
## Data   : all data are simulated from N_p(0, Sigma), Theta = Sigma^{-1}
##          generated by huge::huge.generator (band, random, hub, scale-free).
##
## Requirements: R >= 4.1; packages huge, glmnet, fdrtool, igraph.
## Usage  : Rscript sim_ridge_support.R          full study, 100 replicates
##          Rscript sim_ridge_support.R quick    5 replicates, smoke test
## Output : ../results/*.csv, ../results/*.rds and ../figs/*.pdf
###############################################################################

