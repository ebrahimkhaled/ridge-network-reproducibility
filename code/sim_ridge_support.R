## ---------------------------------------------------------------------------
## 7. Effective penalty and its floor over a (lambda, p / n) grid
## ---------------------------------------------------------------------------
## For the band model with p = 200 we compare kappa_hat with the Monte Carlo
## value of kappa_n = lambda (1 + delta_n), delta_n = tr(Sigma E Q_{-1}) / n,
## and with the lower bound lambda + sigma_min (p - n + 1)_+ / n.
if (!exists("SKIP_MAIN")) {
  set.seed(7)
  pk <- 200
  mk <- huge.generator(d = pk, graph = "band", g = 1, v = 0.4, u = 0.1,
                       verbose = FALSE)
  Sk <- as.matrix(mk$sigma); Ck <- chol(Sk)
  smin <- min(eigen(Sk, TRUE, only.values = TRUE)$values)
  kap_tab <- expand.grid(lambda = c(0.01, 0.1, 0.5, 1), n = c(50, 100, 200, 400, 800))
  kap_tab$kappa_hat <- kap_tab$kappa_mc <- kap_tab$floor <- NA
  for (i in seq_len(nrow(kap_tab))) {
    l <- kap_tab$lambda[i]; nn <- kap_tab$n[i]
    kh <- dl <- numeric(40)
    for (r in 1:40) {
      X <- matrix(rnorm(nn * pk), nn, pk) %*% Ck
      kh[r] <- kappa_hat(spec_S(crossprod(X) / nn), l, nn)
      Xm <- X[-1, , drop = FALSE]          # leave one observation out
      Qm <- solve(crossprod(Xm) / nn + l * diag(pk))
      dl[r] <- sum(Sk * Qm) / nn
    }
    kap_tab$kappa_hat[i] <- mean(kh)
    kap_tab$kappa_mc[i] <- l * (1 + mean(dl))
    kap_tab$floor[i] <- l + smin * max(0, pk - nn + 1) / nn
  }
  write.csv(kap_tab, file.path(OUT, "results", "sim_kappa_grid.csv"),
            row.names = FALSE)
}

## ---------------------------------------------------------------------------
## 8. (n, p) timing benchmark
## ---------------------------------------------------------------------------
## Wall-clock seconds for: one ridge fit with kappa_hat and partial
## correlations, the two-point extrapolation, the MPS selection (99
## permutations, four penalties) and a 30-point graphical lasso path.
if (!exists("SKIP_MAIN")) {
  set.seed(8)
  tim <- NULL
  for (pp in c(100, 200, 400, 800)) {
    nn <- pp / 2
    X <- matrix(rnorm(nn * pp), nn, pp)
    X <- scale(X, TRUE, FALSE)
    S <- crossprod(X) / nn
    t_ridge <- system.time({
      sp <- spec_S(S); R <- pcor_of(ridge_Q(sp, 1)); k <- kappa_hat(sp, 1, nn)
    })[3]
    t_rich <- system.time(richardson_Q(spec_S(S), nn, 1))[3]
    t_mps <- system.time(mps_select(X))[3]
    t_gl <- system.time(huge(X, method = "glasso", nlambda = 30,
                             lambda.min.ratio = 0.01, verbose = FALSE))[3]
    tim <- rbind(tim, data.frame(p = pp, n = nn, ridge = t_ridge,
                                 extrap = t_rich, mps = t_mps, glasso = t_gl))
    cat(sprintf("timing p=%d done\n", pp))
  }
  write.csv(tim, file.path(OUT, "results", "sim_timing.csv"),
            row.names = FALSE)
}

