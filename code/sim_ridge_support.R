## 5. Monte Carlo design
## ---------------------------------------------------------------------------

p_sim  <- 100
n_grid <- c(50, 100, 200, 400)
graphs <- c("band", "random", "hub", "scale-free")

make_model <- function(graph, p) {
  set.seed(switch(graph, band = 11, random = 12, hub = 13, "scale-free" = 14))
  g <- switch(graph,
    band         = huge.generator(d = p, graph = "band", g = 1, v = 0.4,
                                  u = 0.1, verbose = FALSE),
    random       = huge.generator(d = p, graph = "random", prob = 3 / p,
                                  v = 0.3, u = 0.1, verbose = FALSE),
    hub          = huge.generator(d = p, graph = "hub", g = 5, v = 0.3,
                                  u = 0.1, verbose = FALSE),
    "scale-free" = huge.generator(d = p, graph = "scale-free", v = 0.3,
                                  u = 0.1, verbose = FALSE))
  Sig <- as.matrix(g$sigma)
  Theta <- solve(Sig)
  E <- abs(Theta) > 1e-8
  diag(E) <- FALSE
  list(Sig = Sig, Theta = Theta, E = E, D = graph_dist(E))
}

